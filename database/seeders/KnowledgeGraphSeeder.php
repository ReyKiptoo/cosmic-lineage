    public function run(): void
    {
        $dataPath = database_path('data/knowledge_graph.json');
        
        // Ensure data directory exists
        if (! File::exists(dirname($dataPath))) {
            File::makeDirectory(dirname($dataPath), 0755, true);
        }

        $dataset = $this->buildFullDataset();

        // Save to clean JSON for portable export
        File::put($dataPath, json_encode($dataset, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE));

        // Seed Database Tables
        Connection::truncate();
        Experiment::truncate();
        Person::truncate();
        Age::truncate();

        foreach ($dataset['ages'] as $ageData) {
            Age::create($ageData);
        }

        foreach ($dataset['people'] as $personData) {
            Person::create($personData);
        }

        foreach ($dataset['experiments'] as $expData) {
            Experiment::create($expData);
        }

        foreach ($dataset['connections'] as $connData) {
            Connection::create($connData);
        }
    }

